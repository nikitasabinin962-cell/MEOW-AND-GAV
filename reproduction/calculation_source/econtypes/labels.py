def label(k: str) -> str:
    if k.startswith("m_"):
        from .metrics import METRICS
        return METRICS.get(k[2:], (k,))[0]
    if k == "proc_ufa_sh":
        from . import region as R
        if R.CAPITAL != "ГО Уфа":
            return f"Госзаказ у поставщиков из регионального центра ({R.CAPITAL.split(' ', 1)[-1]})"
    return FEATS.get(k, (k,))[0]


def fmt(k: str, v) -> str:
    if v is None or v != v:
        return "н/д"
    u = FEATS.get(k, ("", ""))[1]
    if u == "%":
        return f"{v * 100:.1f}%"
    if abs(v) >= 1000:
        return f"{v:,.0f}".replace(",", " ") + (f" {u}" if u else "")
    return f"{v:.1f}" + (f" {u}" if u else "")
